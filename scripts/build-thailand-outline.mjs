// One-off generator: Thailand outline from Natural Earth (world-atlas) -> src/lib/login-scene/data/thailandOutline.ts
// Usage (deps are NOT added to the project):
//   mkdir /tmp/geo && cd /tmp/geo && npm i world-atlas@2 topojson-client
//   node scripts/build-thailand-outline.mjs /tmp/geo
import { createRequire } from "node:module";
import { writeFileSync, readFileSync } from "node:fs";
import path from "node:path";

const dir = path.resolve(process.argv[2] ?? ".");
const require = createRequire(path.join(dir, "x.js"));
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-10m.json"), "utf8"));
const { feature } = require("topojson-client");
const th = feature(topo, topo.objects.countries).features.find((f) => String(f.id) === "764");
if (!th) throw new Error("Thailand (764) not found");

// polygons: [ring][point][lon,lat]; keep rings that matter (mainland + big islands)
const polys = th.geometry.type === "Polygon" ? [th.geometry.coordinates] : th.geometry.coordinates;
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + (p[0] * q[1] - q[0] * p[1]); }, 0) / 2);

// Douglas-Peucker
function simplify(pts, eps) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let dmax = 0, idx = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs((b[1] - a[1]) * pts[i][0] - (b[0] - a[0]) * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / Math.hypot(b[1] - a[1], b[0] - a[0] || 1e-9);
    if (d > dmax) { dmax = d; idx = i; }
  }
  if (dmax > eps) return [...simplify(pts.slice(0, idx + 1), eps).slice(0, -1), ...simplify(pts.slice(idx), eps)];
  return [a, b];
}

const rings = polys
  .map((p) => p[0]) // outer ring only
  .filter((r) => area(r) > 0.04) // drop tiny islets
  .map((r) => {
    // closed ring: split at the point farthest from the start so Douglas-Peucker has a real baseline
    let k = 0, dm = 0;
    r.forEach((p, i) => { const d = Math.hypot(p[0] - r[0][0], p[1] - r[0][1]); if (d > dm) { dm = d; k = i; } });
    const s = [...simplify(r.slice(0, k + 1), 0.02).slice(0, -1), ...simplify(r.slice(k), 0.02).slice(0, -1)];
    return s.map(([x, y]) => [+x.toFixed(3), +y.toFixed(3)]);
  })
  .filter((r) => r.length >= 4);

const total = rings.reduce((s, r) => s + r.length, 0);
const out = `// GENERATED by scripts/build-thailand-outline.mjs from Natural Earth 10m (public domain) via world-atlas. Do not edit.
// Rings of [longitude, latitude]; outer boundaries only, simplified. ${rings.length} rings, ${total} points.
export const THAILAND_RINGS: ReadonlyArray<ReadonlyArray<readonly [number, number]>> = ${JSON.stringify(rings)};
`;
writeFileSync("src/lib/login-scene/data/thailandOutline.ts", out);
console.log(rings.length, "rings", total, "points", out.length, "bytes");
